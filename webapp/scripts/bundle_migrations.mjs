#!/usr/bin/env node
// Version 3.46: migrations/*.sql bundled into src/migrations.js, so the
// Worker can apply them itself (POST /api/ingest/migrate) - the deploy
// token does not need D1 Edit. `--check` fails when the bundle is stale.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';

const dir = new URL('../migrations/', import.meta.url);
const out = new URL('../src/migrations.js', import.meta.url);
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const list = files.map((f) => ({ name: f, sql: readFileSync(new URL(f, dir), 'utf8') }));
const text = '// Generated by scripts/bundle_migrations.mjs from migrations/*.sql - do not edit.\n'
  + `export const MIGRATIONS = ${JSON.stringify(list, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const now = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (now !== text) { console.error('src/migrations.js is stale: run node scripts/bundle_migrations.mjs'); process.exit(1); }
  console.log(`migrations bundle: ${files.length} files, up to date`);
} else {
  writeFileSync(out, text);
  console.log(`src/migrations.js: ${files.length} migrations`);
}
